let LANG = 'en';

function t(key, vars) {
    const table = I18N[LANG] || I18N.en;
    let str = table[key] || I18N.en[key] || key;
    if (vars) {
        str = str.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? '' : String(vars[name])));
    }
    return str;
}

function applyI18n() {
    document.documentElement.lang = LANG;
    document.title = t('docTitle');
    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute('content', t('docDesc'));

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (el.getAttribute('data-i18n-html') === '1') el.innerHTML = t(key);
        else el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
        el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
    document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
        el.setAttribute('alt', t(el.getAttribute('data-i18n-alt')));
    });

    document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
        btn.classList.toggle('is-on', btn.getAttribute('data-lang-btn') === LANG);
    });

    if (typeof STATE !== 'undefined' && STATE.cards) {
        STATE.cards.frente.name = t('front');
        STATE.cards.dorso.name = t('back');
    }
    if (typeof FACTORY_DEFAULTS !== 'undefined' && FACTORY_DEFAULTS.cards) {
        FACTORY_DEFAULTS.cards.frente.name = t('front');
        FACTORY_DEFAULTS.cards.dorso.name = t('back');
    }
}

function initLang() {
    const saved = localStorage.getItem('cardpdf-lang');
    LANG = saved === 'es' ? 'es' : 'en';
    applyI18n();
}

function setLang(next) {
    const lang = next === 'es' ? 'es' : 'en';
    if (lang === LANG) return;
    LANG = lang;
    localStorage.setItem('cardpdf-lang', lang);
    applyI18n();
    if (typeof updateUIFromState === 'function') updateUIFromState();
    if (typeof updatePaperThemeUI === 'function') updatePaperThemeUI();
    if (typeof updateDefaultConfigBadge === 'function') updateDefaultConfigBadge();
    if (typeof scheduleRender === 'function') scheduleRender();
}

